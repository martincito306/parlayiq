from typing import Dict, Any
from fastapi import APIRouter
from app.schemas.predictions import ParlayEvaluateRequest
from app.services.parlay_service import parlay_service

router = APIRouter(prefix="/parlay", tags=["Parlays & Same Game Parlays"])


@router.post("/evaluate")
async def evaluate_parlay(request: ParlayEvaluateRequest) -> Dict[str, Any]:
    """
    Evaluates a user-defined Parlay / Same Game Parlay (SGP) using
    10,000 vectorised Monte Carlo simulations and Gaussian Copula.
    Includes Smart Slip Auditor diagnostics for weak legs.
    """
    legs_dicts = [leg.model_dump() for leg in request.legs]
    return await parlay_service.evaluate_custom_parlay(
        legs=legs_dicts,
        num_simulations=request.num_simulations
    )


@router.get("/daily")
async def get_daily_parlays() -> Dict[str, Any]:
    """
    Daily Parlay Intelligence: Returns Conservative, Balanced, and High-Yield
    curated tickets generated by scanning today's fixtures.
    """
    return await parlay_service.get_daily_parlays()
